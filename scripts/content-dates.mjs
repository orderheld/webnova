/**
 * Writes src/content/dates.ts: the date each content file last changed, used as lastmod in the sitemap.
 * Files with uncommitted changes get today's date. Run `npm run content-dates` after changing page texts.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = "src/content";
const out = join(root, "dates.ts");
const git = (...args) => execFileSync("git", args, { encoding: "utf8" }).trim();

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith(".ts") && p !== out) files.push(p);
  }
})(root);

const changed = new Set(git("diff", "--name-only", "HEAD", "--", root).split("\n").filter(Boolean));
const today = new Date().toISOString().slice(0, 10);
const dates = {};
for (const p of files.sort()) {
  const d = changed.has(p) ? today : git("log", "-1", "--format=%cs", "--", p);
  if (d) dates[relative(root, p)] = d;
}

writeFileSync(
  out,
  `/** Date each content file last changed, for the sitemap's lastmod. Generated by scripts/content-dates.mjs (npm run content-dates). */\nexport const contentDates: Record<string, string> = ${JSON.stringify(dates, null, 2)};\n`,
);
console.log(`${Object.keys(dates).length} dates written to ${out}`);
